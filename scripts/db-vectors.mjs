// Turns packages/shared/test-vectors/*.json into a pgTAP file so plpgsql is checked against the very
// same cases as the TypeScript domain code (paramnet-domain principle 8). CI fails if the output is stale.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const read = (name) =>
	JSON.parse(readFileSync(`${root}packages/shared/test-vectors/${name}`, "utf8"));
const out = `${root}supabase/tests/database/030_domain_vectors.test.sql`;

const json = (value) => `$v$${JSON.stringify(value)}$v$::jsonb`;
const text = (value) => `$v$${value}$v$`;
const name = (value) => text(value);

const lines = [];
function expectResult(call, expected, label) {
	if (expected.ok) {
		lines.push(
			`select is(${call}, ${json(expected.plan ?? expected.allocations)}, ${name(label)});`,
		);
	} else {
		// Outer tag differs from the $v$ literals inside the statement.
		lines.push(
			`select throws_ok($q$select ${call}$q$, 'P0001', ${text(expected.error)}, ${name(label)});`,
		);
	}
}

const plan = read("plan.json");
for (const vector of plan.generate) {
	expectResult(
		`private.generate_plan(${json(vector.input)})`,
		vector.expected,
		`generate: ${vector.name}`,
	);
}
for (const vector of plan.validate) {
	expectResult(
		`private.validate_plan(${json(vector.input)})`,
		vector.expected,
		`validate: ${vector.name}`,
	);
}
for (const vector of read("allocation.json").allocate) {
	expectResult(
		`private.allocate_payment(${json(vector.input)})`,
		vector.expected,
		`allocate: ${vector.name}`,
	);
}
for (const vector of read("terms-hash.json").vectors) {
	lines.push(
		`select is(private.canonical_json(${json(vector.terms)}), ${text(vector.canonical)}, ${name(`canonical: ${vector.name}`)});`,
	);
	lines.push(
		`select is(private.terms_hash(${json(vector.terms)}), ${text(vector.sha256)}, ${name(`terms_hash: ${vector.name}`)});`,
	);
}

// SQL null and a text literal: is() compares them with IS NOT DISTINCT FROM.
const textOrNull = (value) => (value === null ? "null::text" : text(value));
const ids = read("profile-ids.json");
for (const vector of ids.paramnet_id) {
	lines.push(
		`select is(private.normalize_paramnet_id(${text(vector.input)}), ${textOrNull(vector.expected)}, ${name(`paramnet_id: ${vector.name}`)});`,
	);
}
for (const vector of ids.username) {
	lines.push(
		`select is(private.normalize_username(${text(vector.input)}), ${textOrNull(vector.expected)}, ${name(`username: ${vector.name}`)});`,
	);
}
for (const vector of read("accounts.json").categories) {
	lines.push(
		`select is(private.is_category_for(${text(vector.kind)}, ${text(vector.category)}), ${String(vector.expected)}, ${name(`category: ${vector.name}`)});`,
	);
}
// SQL arrays of dates read back as a JSON array of strings.
const dates = (call) => `to_jsonb(${call})`;
const recurrence = read("recurrence.json");
for (const vector of recurrence.next) {
	lines.push(
		`select is(${dates(`private.next_occurrences(${text(vector.start)}, ${text(vector.frequency)}, ${text(vector.from)}, ${String(vector.count)})`)}, ${json(vector.expected)}, ${name(`next: ${vector.name}`)});`,
	);
}
for (const vector of recurrence.between) {
	lines.push(
		`select is(${dates(`private.recurrence_dates(${text(vector.start)}, ${text(vector.frequency)}, ${text(vector.from)}, ${text(vector.to)})`)}, ${json(vector.expected)}, ${name(`between: ${vector.name}`)});`,
	);
}
const cards = read("cards.json");
for (const vector of cards.cuts) {
	lines.push(
		`select is(private.card_cuts(${text(vector.today)}, ${String(vector.statement_day)}), ${json({ last: vector.last, next: vector.next })}, ${name(`card cuts: ${vector.name}`)});`,
	);
}
for (const vector of cards.parts) {
	lines.push(
		`select is(to_jsonb(private.installment_parts(${String(vector.amount)}, ${String(vector.count)})), ${json(vector.expected)}, ${name(`parts: ${vector.name}`)});`,
	);
}
for (const vector of cards.states) {
	lines.push(
		`select is(private.card_state_from(${json(vector.card)}, ${json(vector.transactions)}, ${text(vector.today)}), ${json(vector.expected)}, ${name(`card: ${vector.name}`)});`,
	);
}
const loans = read("loans.json");
for (const vector of loans.payments) {
	lines.push(
		`select is(private.loan_payment(${String(vector.principal)}, ${String(vector.bps)}, ${String(vector.term)}), ${String(vector.expected)}::bigint, ${name(`loan payment: ${vector.name}`)});`,
	);
}
for (const vector of loans.schedules) {
	lines.push(
		`select is(private.loan_schedule(${String(vector.principal)}, ${String(vector.bps)}, ${String(vector.term)}, ${text(vector.first_due)}, ${String(vector.installment)}), ${json(vector.expected)}, ${name(`loan schedule: ${vector.name}`)});`,
	);
}

writeFileSync(
	out,
	[
		"-- GENERATED by scripts/db-vectors.mjs from packages/shared/test-vectors; do not edit. Run: pnpm db:vectors",
		"begin;",
		`select plan(${String(lines.length)});`,
		"",
		...lines,
		"",
		"select * from finish();",
		"rollback;",
		"",
	].join("\n"),
);
console.log(`wrote ${String(lines.length)} assertions to ${out}`);
